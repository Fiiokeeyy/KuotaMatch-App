    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        try {
            Connection conn = koneksi.KoneksiDB.getKoneksi();

            // 1. Ambil nama provider dari ComboBox dan cari id_provider-nya di database
            String namaProv = comboProvider.getSelectedItem().toString();
            String sqlCariProv = "SELECT id_provider FROM Provider WHERE nama_provider = '" + namaProv + "'";

            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sqlCariProv);

            if(rs.next()) {
                int idProv = rs.getInt("id_provider");

                // 2. Siapkan perintah INSERT ke tabel Paket_Data
                String sqlInsert = "INSERT INTO Paket_Data (id_provider, nama_paket, harga, kuota_gb, masa_aktif_hari, skor_sinyal) VALUES (?, ?, ?, ?, ?, ?)";

                PreparedStatement pst = conn.prepareStatement(sqlInsert);
                pst.setInt(1, idProv);
                pst.setString(2, txtNamaPaket.getText());
                pst.setInt(3, Integer.parseInt(txtHargaPaket.getText()));
                pst.setInt(4, Integer.parseInt(txtKuotaPaket.getText()));
                pst.setInt(5, Integer.parseInt(txtMasaAktifPaket.getText()));
                pst.setInt(6, Integer.parseInt(txtSinyalPaket.getText()));

                // 3. Eksekusi penyimpanan
                pst.execute();
                JOptionPane.showMessageDialog(this, "Mantap! Data Paket Baru Berhasil Ditambahkan.");

                // Opsi: Tutup jendela ini setelah selesai menyimpan
                this.dispose();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Periksa lagi! Harga, Kuota, Masa Aktif, dan Sinyal harus diisi dengan angka.");
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + ex.getMessage());
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

