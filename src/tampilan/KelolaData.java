    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        // TODO add your handling code here:
        if (idTerpilih == 0) {
            JOptionPane.showMessageDialog(this, "Silahkan pilih data pada tabel terlebih dahulu!");
            return;
        }

        try {
            Connection conn = koneksi.KoneksiDB.getKoneksi();

            // Cari id_provider berdasarkan nama di ComboBox
            String namaProv = comboProvider.getSelectedItem().toString();
            String sqlCariProv = "SELECT id_provider FROM Provider WHERE nama_provider = '" + namaProv + "'";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sqlCariProv);

            if (rs.next()) {
                int idProv = rs.getInt("id_provider");

                // Query Update
                String sqlUpdate = "UPDATE Paket_Data SET id_provider=?, nama_paket=?, harga=?, kuota_gb=?, masa_aktif_hari=?, skor_sinyal=? WHERE id_paket=?";
                PreparedStatement pst = conn.prepareStatement(sqlUpdate);
                pst.setInt(1, idProv);
                pst.setString(2, txtNamaPaket.getText());
                pst.setInt(3, Integer.parseInt(txtHargaPaket.getText()));
                pst.setInt(4, Integer.parseInt(txtKuotaPaket.getText()));
                pst.setInt(5, Integer.parseInt(txtMasaAktifPaket.getText()));
                pst.setInt(6, Integer.parseInt(txtSinyalPaket.getText()));
                pst.setInt(7, idTerpilih);

                pst.execute();
                JOptionPane.showMessageDialog(this, "Data Berhasil Diperbarui!");
                tampilDataMentah(); // Refresh tabel otomatis
                idTerpilih = 0; // Reset ID
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mengubah data: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUbahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        if (idTerpilih == 0) {
            JOptionPane.showMessageDialog(this, "Silahkan pilih data pada tabel terlebih dahulu!");
            return;
        }

        int konfirmasi = JOptionPane.showConfirmDialog(this, "Yakin nih mau menghapus paket ini?", "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);
        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                Connection conn = koneksi.KoneksiDB.getKoneksi();
                String sqlDelete = "DELETE FROM Paket_Data WHERE id_paket = ?";
                PreparedStatement pst = conn.prepareStatement(sqlDelete);
                pst.setInt(1, idTerpilih);

                pst.execute();
                JOptionPane.showMessageDialog(this, "Data Berhasil Dihapus!");
                tampilDataMentah(); // Refresh tabel
                idTerpilih = 0; // Reset ID
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus data: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

