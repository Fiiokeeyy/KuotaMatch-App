    public void tampilDataMentah() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("Provider");
        model.addColumn("Nama Paket");
        model.addColumn("Harga");
        model.addColumn("Kuota (GB)");
        model.addColumn("Masa Aktif");
        model.addColumn("Sinyal");

        try {
            Connection conn = koneksi.KoneksiDB.getKoneksi();
            String sql = "SELECT p.id_paket, pr.nama_provider, p.nama_paket, p.harga, p.kuota_gb, p.masa_aktif_hari, p.skor_sinyal " +
                         "FROM Paket_Data p JOIN Provider pr ON p.id_provider = pr.id_provider";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("id_paket"),
                    rs.getString("nama_provider"),
                    rs.getString("nama_paket"),
                    rs.getInt("harga"),
                    rs.getInt("kuota_gb"),
                    rs.getInt("masa_aktif_hari"),
                    rs.getInt("skor_sinyal")
                });
            }
            tabelPaket.setModel(model);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat data: " + e.getMessage());
        }
    }
    
